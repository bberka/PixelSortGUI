#!/bin/sh
# Runs .hooks/commit-msg against sample messages. Exits non-zero if any case gives the wrong result.
# Usage: sh .hooks/test-commit-msg.sh

dir=$(cd "$(dirname "$0")" && pwd)
hook="$dir/commit-msg"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM

failures=0
total=0

# check <name> <pass|reject> <message>
check() {
	name=$1
	expect=$2
	printf '%s\n' "$3" > "$tmp/msg"
	total=$((total + 1))
	if "$hook" "$tmp/msg" > /dev/null 2>&1; then
		got=pass
	else
		got=reject
	fi
	if [ "$got" = "$expect" ]; then
		echo "ok      $name ($expect)"
	else
		echo "FAILED  $name: expected $expect, got $got"
		failures=$((failures + 1))
	fi
}

check "clean message" pass "feat: add threshold sorter

Sorts spans between the two thresholds."

check "subject only" pass "fix: clamp span length"

check "trailer" reject "feat: add mask

Co-authored-by: Some Agent <agent@example.com>"

check "trailer lower case" reject "feat: add mask

co-authored-by: Some Agent <agent@example.com>"

check "trailer upper case" reject "feat: add mask

CO-AUTHORED-BY: Some Agent <agent@example.com>"

check "trailer mixed case" reject "feat: add mask

Co-Authored-By: Some Agent <agent@example.com>"

check "trailer after blank line, other trailers around" reject "fix: clamp span length

Closes #4

Co-authored-by: Some Agent <agent@example.com>
Signed-off-by: Owner <owner@example.com>"

check "trailer with space before colon" reject "fix: clamp span length

Co-authored-by : Some Agent <agent@example.com>"

check "indented trailer" reject "fix: clamp span length

   Co-authored-by: Some Agent <agent@example.com>"

check "generated with line" reject "feat: add mask

Generated with Claude Code"

check "generated with emoji and link" reject "feat: add mask

🤖 Generated with [Claude Code](https://claude.com/claude-code)"

check "generated by lower case" reject "feat: add mask

generated by some tool"

check "prose mentions co-author" pass "docs: explain the ban on co-author trailers

A co-author line in a commit is not allowed here. The pull request names the agents."

check "prose mentions co-authored-by mid line" pass "docs: explain the trailer ban

The hook rejects a Co-authored-by: trailer at the start of a line."

check "prose uses generated with mid line" pass "feat: show the span map

The preview is generated with the same worker as the export."

check "trailer only in text below scissors line" pass "feat: add mask

# ------------------------ >8 ------------------------
diff --git a/x b/x
 Co-authored-by: Some Agent <agent@example.com>"

if "$hook" "$tmp/does-not-exist" > /dev/null 2>&1; then
	echo "FAILED  missing file: expected reject, got pass"
	failures=$((failures + 1))
else
	echo "ok      missing file (reject)"
fi
total=$((total + 1))

echo "$((total - failures)) of $total cases correct"
[ "$failures" -eq 0 ]
