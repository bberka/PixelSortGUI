import fs from 'node:fs';
import path from 'node:path';
import type {Plugin} from 'vite-plus';

export function changelogPaths(rootDir: string) {
	return {
		source: path.join(rootDir, 'CHANGELOG.md'),
		output: path.join(rootDir, 'src/features/settings/changelog.generated.ts'),
	} as const;
}

export function renderChangelogModule(markdown: string): string {
	const text = markdown
		.replaceAll('\r\n', '\n')
		.replaceAll('\\', '\\\\')
		.replaceAll('`', '\\`')
		.replaceAll('${', '\\${');
	return `// Generated by scripts/gen-changelog.ts from CHANGELOG.md. Do not edit.
export const CHANGELOG_TEXT = \`${text}\`;
`;
}

export function isChangelogCurrent(rootDir: string): boolean {
	const {source, output} = changelogPaths(rootDir);
	return (
		fs.existsSync(output) &&
		fs.readFileSync(output, 'utf8') ===
			renderChangelogModule(fs.readFileSync(source, 'utf8'))
	);
}

/**
Fails the production build when the bundled release notes differ from CHANGELOG.md.
*/
export function changelogCheck(rootDir: string): Plugin {
	return {
		name: 'drift-changelog',
		apply: 'build',
		buildStart() {
			if (!isChangelogCurrent(rootDir)) {
				this.error(
					'The bundled changelog does not match CHANGELOG.md. Run "pnpm run gen:changelog" and commit the result.',
				);
			}
		},
	};
}
