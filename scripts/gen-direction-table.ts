import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import {pathToFileURL} from 'node:url';
import {roundHalfAway} from '../src/engine/math.ts';

export const DIRECTION_TABLE_LENGTH = 3600;
const SCALE = 4096;

const EXACT_CARDINALS = new Map<number, readonly [number, number]>([
	[0, [SCALE, 0]],
	[900, [0, -SCALE]],
	[1800, [-SCALE, 0]],
	[2700, [0, SCALE]],
]);

function normalizeZero(value: number): number {
	return value === 0 ? 0 : value;
}

export function computeDirectionTable(): Array<readonly [number, number]> {
	const entries: Array<readonly [number, number]> = [];
	for (let a = 0; a < DIRECTION_TABLE_LENGTH; a++) {
		const exact = EXACT_CARDINALS.get(a);
		if (exact !== undefined) {
			entries.push(exact);
			continue;
		}

		const theta = ((a / 10) * Math.PI) / 180;
		const dx = normalizeZero(roundHalfAway(SCALE * Math.cos(theta)));
		const dy = normalizeZero(roundHalfAway(-SCALE * Math.sin(theta)));
		entries.push([dx, dy]);
	}

	return entries;
}

export function generateDirectionTableSource(): string {
	const entries = computeDirectionTable();
	const lines = [
		'// Generated by scripts/gen-direction-table.ts. Do not edit by hand.',
		'export const DIRECTION_TABLE: ReadonlyArray<readonly [number, number]> = [',
	];

	for (const [dx, dy] of entries) {
		lines.push(`\t[${dx}, ${dy}],`);
	}

	lines.push('];', '');
	return lines.join('\n');
}

export const defaultOutputPath = path.resolve(
	import.meta.dirname,
	'../src/engine/direction-table.ts',
);

if (
	process.argv[1] !== undefined &&
	import.meta.url === pathToFileURL(process.argv[1]).href
) {
	const checkOnly = process.argv.includes('--check');
	const expected = generateDirectionTableSource();

	if (checkOnly) {
		const actual = readFileSync(defaultOutputPath, 'utf8');
		if (actual === expected) {
			console.log('src/engine/direction-table.ts is up to date.');
		} else {
			console.error(
				'src/engine/direction-table.ts is stale. Run `node scripts/gen-direction-table.ts` to regenerate it.',
			);
			process.exitCode = 1;
		}
	} else {
		writeFileSync(defaultOutputPath, expected, 'utf8');
		console.log(
			`Wrote ${defaultOutputPath} (${DIRECTION_TABLE_LENGTH} entries).`,
		);
	}
}
