import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import {pathToFileURL} from 'node:url';
import {roundHalfAway} from '../src/engine/math.ts';

export const LANCZOS_TABLE_LENGTH = 1024;
// Entries per unit of kernel distance, so t = 1, 2 and 3 fall on entries.
const STEPS = 341;
const SCALE = 2 ** 22;

export function computeLanczosTable(): number[] {
	return Array.from({length: LANCZOS_TABLE_LENGTH}, (_, i) => {
		if (i === 0) {
			return SCALE;
		}

		// `Math.sin(Math.PI * k)` is not exactly 0.
		if (i % STEPS === 0) {
			return 0;
		}

		const x = (Math.PI * i) / STEPS;
		return roundHalfAway((SCALE * 3 * Math.sin(x) * Math.sin(x / 3)) / (x * x));
	});
}

// Matches the `unicorn/numeric-separators-style` lint rule.
function literal(value: number): string {
	const digits = String(Math.abs(value));
	const grouped =
		digits.length < 5 ? digits : digits.replaceAll(/\B(?=(?:\d{3})+$)/g, '_');
	return value < 0 ? `-${grouped}` : grouped;
}

export function generateLanczosTableSource(): string {
	const lines = [
		'// Generated by scripts/gen-lanczos-table.ts. Do not edit by hand.',
		'// prettier-ignore',
		'export const LANCZOS_TABLE: readonly number[] = [',
	];
	const values = computeLanczosTable().map((value) => literal(value));
	for (let i = 0; i < values.length; i += 8) {
		lines.push(`\t${values.slice(i, i + 8).join(', ')},`);
	}

	lines.push('];', '');
	return lines.join('\n');
}

export const defaultOutputPath = path.resolve(
	import.meta.dirname,
	'../src/engine/lanczos-table.ts',
);

if (
	process.argv[1] !== undefined &&
	import.meta.url === pathToFileURL(process.argv[1]).href
) {
	const checkOnly = process.argv.includes('--check');
	const expected = generateLanczosTableSource();

	if (checkOnly) {
		const actual = readFileSync(defaultOutputPath, 'utf8');
		if (actual === expected) {
			console.log('src/engine/lanczos-table.ts is up to date.');
		} else {
			console.error(
				'src/engine/lanczos-table.ts is stale. Run `node scripts/gen-lanczos-table.ts` to regenerate it.',
			);
			process.exitCode = 1;
		}
	} else {
		writeFileSync(defaultOutputPath, expected, 'utf8');
		console.log(
			`Wrote ${defaultOutputPath} (${LANCZOS_TABLE_LENGTH} entries).`,
		);
	}
}
