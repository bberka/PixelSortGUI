import fs from 'node:fs';
import path from 'node:path';

type PackageJson = {
	name?: string;
	version?: string;
	license?: string | {type?: string};
	homepage?: string;
	repository?: string | {url?: string};
	dependencies?: Record<string, string>;
};

type ThirdPartyNotice = {
	name: string;
	version: string;
	license: string;
	url?: string;
};

const rootDir = path.resolve(import.meta.dirname, '..');
const rootPkgPath = path.join(rootDir, 'package.json');
const rootLicensePath = path.join(rootDir, 'LICENSE');
const outputPath = path.join(
	rootDir,
	'src/features/settings/third-party-notices.generated.ts',
);

function normalizeLicense(value: PackageJson['license']): string {
	if (typeof value === 'string' && value.trim().length > 0) {
		return value.trim();
	}

	return value && typeof value === 'object' && typeof value.type === 'string'
		? value.type.trim()
		: 'Unknown';
}

function normalizeUrl(pkg: PackageJson): string | undefined {
	const raw =
		typeof pkg.homepage === 'string' && pkg.homepage.trim().length > 0
			? pkg.homepage.trim()
			: typeof pkg.repository === 'string'
				? pkg.repository.trim()
				: typeof pkg.repository?.url === 'string'
					? pkg.repository.url.trim()
					: undefined;

	if (!raw) {
		return undefined;
	}

	let cleaned = raw.replace(/^git\+/, '').replace(/\.git$/, '');
	if (cleaned.startsWith('github:')) {
		cleaned = `https://github.com/${cleaned.slice('github:'.length)}`;
	}

	return cleaned.startsWith('https://') ? cleaned : undefined;
}

function readJson(filePath: string): PackageJson {
	return JSON.parse(fs.readFileSync(filePath, 'utf8')) as PackageJson;
}

function quoteSingle(value: string): string {
	return `'${value
		.replaceAll('\\', '\\\\')
		.replaceAll("'", String.raw`\'`)
		.replaceAll('\n', String.raw`\n`)}'`;
}

function main() {
	const rootPkg = readJson(rootPkgPath);
	const depNames = Object.keys(rootPkg.dependencies ?? {}).toSorted((a, b) =>
		a.localeCompare(b, 'en'),
	);

	const notices: ThirdPartyNotice[] = [];
	for (const depName of depNames) {
		const depPkgPath = path.join(
			rootDir,
			'node_modules',
			depName,
			'package.json',
		);
		if (!fs.existsSync(depPkgPath)) {
			throw new Error(`Missing installed dependency manifest: ${depPkgPath}`);
		}

		const depPkg = readJson(depPkgPath);
		const entry: ThirdPartyNotice = {
			name: depPkg.name ?? depName,
			version: depPkg.version ?? '0.0.0',
			license: normalizeLicense(depPkg.license),
		};
		const url = normalizeUrl(depPkg);
		if (url) {
			entry.url = url;
		}

		notices.push(entry);
	}

	const appLicenseText = fs.readFileSync(rootLicensePath, 'utf8').trim();

	const noticeLines = notices.map((entry) => {
		const fields = [
			`\t\tname: ${quoteSingle(entry.name)},`,
			`\t\tversion: ${quoteSingle(entry.version)},`,
			`\t\tlicense: ${quoteSingle(entry.license)},`,
		];
		if (entry.url) {
			fields.push(`\t\turl: ${quoteSingle(entry.url)},`);
		}

		return `\t{\n${fields.join('\n')}\n\t},`;
	});

	const lines = [
		'// Generated by scripts/gen-notices.ts from package.json dependencies and LICENSE.',
		'export type ThirdPartyNotice = {',
		'\treadonly name: string;',
		'\treadonly version: string;',
		'\treadonly license: string;',
		'\treadonly url?: string;',
		'};',
		'',
		'export const THIRD_PARTY_NOTICES: readonly ThirdPartyNotice[] = [',
		...noticeLines,
		'];',
		'',
		`export const APP_LICENSE_TEXT = ${quoteSingle(appLicenseText)};`,
		'',
	];

	fs.mkdirSync(path.dirname(outputPath), {recursive: true});
	fs.writeFileSync(outputPath, lines.join('\n'), 'utf8');
}

main();
